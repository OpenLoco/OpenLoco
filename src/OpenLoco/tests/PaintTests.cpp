    TEST(PaintTest, tileStrideIsOneUntilATileIsSmallerThanAPixel)
    {
        // A tile is 32 world units, so everything up to 1/32 zoom still has at least a pixel per tile
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::quadrupled), 1);
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::full), 1);
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::eighth), 1);
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::sixteenth), 1);
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::thirtySecond), 1);

        // At 1/64 a pixel covers two tiles, at 1/128 four, and so on
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::sixtyFourth), 2);
        EXPECT_EQ(Paint::tileStrideForZoom(ZoomLevel::hundredTwentyEighth), 4);
    }

    TEST(PaintTest, columnsAreAlwaysAtLeastOnePixelWide)
    {
        // A zero width column used to make the viewport's column loop never terminate, which
        // allocated memory until the system ran out of it
        for (auto level = ZoomLevel::min; level <= ZoomLevel::max; ++level)
        {
            const auto zoom = ZoomLevel{ level };
            EXPECT_GE(Ui::getColumnWidth(zoom), 1) << "zoom level " << static_cast<int32_t>(level);
        }
    }

    TEST(PaintTest, columnWidthCoversWholeTiles)
    {
        // Every column must cover a whole number of tiles so that the tiles generated by the paint
        // session line up with the columns
        for (auto level = ZoomLevel::min; level <= ZoomLevel::max; ++level)
        {
            const auto zoom = ZoomLevel{ level };
            const auto worldWidth = zoom.applyTo<int32_t>(Ui::getColumnWidth(zoom));
            EXPECT_EQ(worldWidth % World::kTileSize, 0) << "zoom level " << static_cast<int32_t>(level);
            EXPECT_GE(worldWidth, World::kTileSize * Paint::tileStrideForZoom(zoom)) << "zoom level " << static_cast<int32_t>(level);
        }
    }

    TEST(PaintTest, solidTileRectanglesCoverTheWholeTileAtEveryZoomLevel)
    {
        // The rectangle that a tile is drawn as (water at the furthest zoom out levels) must always
        // cover at least the pixels that the tile itself maps onto, otherwise parts of the tile keep
        // showing the terrain. A tile is 32 world units, i.e. as many pixels as kTileSize >> zoom.
        for (auto level = ZoomLevel::min; level <= ZoomLevel::max; ++level)
        {
            const auto zoom = ZoomLevel{ level };
            const auto size = Paint::solidTileSizeForZoom(zoom);
            const auto tilePixels = std::max<int32_t>(1, zoom.applyInversedTo<int32_t>(World::kTileSize));

            EXPECT_GE(size.x, tilePixels) << "zoom level " << static_cast<int32_t>(level);
            EXPECT_GE(size.y, tilePixels) << "zoom level " << static_cast<int32_t>(level);

            // Up to 1/16 a tile is several pixels wide, so its whole bounding box (twice as wide as
            // it is tall) is filled; beyond that a single pixel per tile is exactly one tile's worth
            // of area and keeps the water inside the tile.
            if (tilePixels > 1)
            {
                EXPECT_EQ(size.x, tilePixels * 2) << "zoom level " << static_cast<int32_t>(level);
                EXPECT_EQ(size.y, tilePixels) << "zoom level " << static_cast<int32_t>(level);
            }
            else
            {
                EXPECT_EQ(size.x, 1) << "zoom level " << static_cast<int32_t>(level);
                EXPECT_EQ(size.y, 1) << "zoom level " << static_cast<int32_t>(level);
            }
        }

        // A tile is two pixels across and one pixel down at 1/16, four and two at 1/8 (where water is
        // still drawn as an image, but the rectangle is the same size)
        EXPECT_EQ(Paint::solidTileSizeForZoom(ZoomLevel::sixteenth), (Ui::Point{ 4, 2 }));
        EXPECT_EQ(Paint::solidTileSizeForZoom(ZoomLevel::thirtySecond), (Ui::Point{ 1, 1 }));
        EXPECT_EQ(Paint::solidTileSizeForZoom(ZoomLevel::sixtyFourth), (Ui::Point{ 1, 1 }));
        EXPECT_EQ(Paint::solidTileSizeForZoom(ZoomLevel::hundredTwentyEighth), (Ui::Point{ 1, 1 }));
    }

    // A palette map that is not the identity so that a remapped pixel can be told apart. It is large
    // enough for a few rows so that a blend of a source and a destination pixel is defined as well.
    constexpr size_t kTestPaletteMapSize = Gfx::PaletteMap::kDefaultSize * 8;
    const Gfx::PaletteMap::Buffer<kTestPaletteMapSize>& getTestPaletteMap()
    {
        static const auto paletteMap = [] {
            Gfx::PaletteMap::Buffer<kTestPaletteMapSize> buffer{};
            for (auto i = 0u; i < buffer.size(); i++)
            {
                buffer[i] = static_cast<PaletteIndex_t>(i + 1);
            }
            return buffer;
        }();
        return paletteMap;
    }

    TEST(PaintTest, maskImagesAreDrawnWhenTheSampledPixelIsTransparent)
    {
        // Mask images (water, glass, ...) are drawn by transforming the pixels that are already in the
        // render target; the source image is only a mask. The corners of the diamond shaped map
        // sprites are transparent, so a transparent sample must not stop the image from being drawn.
        constexpr auto kMaskOp = Gfx::DrawBlendOp::transparent | Gfx::DrawBlendOp::dst;
        const Gfx::PaletteMap::View paletteMap{ getTestPaletteMap() };

        const std::array<PaletteIndex_t, 4> block{ PaletteIndex::transparent, 5, PaletteIndex::transparent, PaletteIndex::transparent };

        // A single transparent pixel is not drawn
        auto dst = static_cast<PaletteIndex_t>(3);
        EXPECT_FALSE(Gfx::blitSampledPixel<kMaskOp>(PaletteIndex::transparent, dst, paletteMap, 0xFF, block.data(), 1));
        EXPECT_EQ(dst, 3);

        // A mask image searches the rest of the block instead, so that it is not lost when zoomed out
        EXPECT_TRUE(Gfx::blitSampledPixel<kMaskOp>(PaletteIndex::transparent, dst, paletteMap, 0xFF, block.data(), static_cast<int32_t>(block.size())));
        EXPECT_EQ(dst, paletteMap[3]);

        // Images that are not masks are unaffected
        constexpr auto kNormalOp = Gfx::DrawBlendOp::transparent;
        dst = static_cast<PaletteIndex_t>(3);
        EXPECT_FALSE(Gfx::blitSampledPixel<kNormalOp>(PaletteIndex::transparent, dst, paletteMap, 0xFF, block.data(), static_cast<int32_t>(block.size())));
        EXPECT_EQ(dst, 3);
    }
